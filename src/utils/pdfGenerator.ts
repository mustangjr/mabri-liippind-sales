import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

interface PDFHeaderOptions {
  reportTitle: string;
  periodText?: string;
  generatedBy?: string;
}

export function createBaseDoc(options: PDFHeaderOptions): jsPDF {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const now = new Date();
  const dateFormatted = now.toLocaleDateString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  // Top header banner
  doc.setFillColor(30, 41, 59); // Slate-800
  doc.rect(0, 0, 210, 32, 'F');

  // Mabri Logo
  drawMabriLogo(doc, 14, 6, 8.5, [255, 255, 255]);

  // Company Name
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('MABRI LIMITED', 44, 13);

  // Subtitle
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225); // Slate-300
  doc.text('LIPPINGS STOCK & SALES MANAGEMENT SYSTEM', 44, 20);

  // Report Title Badge
  doc.setFontSize(9.5);
  doc.setTextColor(248, 250, 252);
  doc.text(options.reportTitle.toUpperCase(), 44, 27);

  // Meta info on the right
  doc.setFontSize(8);
  doc.setTextColor(226, 232, 240);
  if (options.periodText) {
    doc.text(`Period: ${options.periodText}`, 196, 12, { align: 'right' });
  }
  doc.text(`Generated: ${dateFormatted}`, 196, 18, { align: 'right' });
  doc.text(`Generated By: ${options.generatedBy || 'Administrator'}`, 196, 24, { align: 'right' });

  // Reset text color for body
  doc.setTextColor(15, 23, 42);

  return doc;
}

export function addDocFooter(doc: jsPDF) {
  const pageCount = (doc as any).internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);

    // Line above footer
    doc.setDrawColor(226, 232, 240);
    doc.line(14, 283, 196, 283);

    doc.text('Mabri Limited • Official Store Stock & Sales Audit Document', 14, 288);
    doc.text(`Page ${i} of ${pageCount}`, 196, 288, { align: 'right' });
  }
}

/**
 * Generate Daily Sales PDF Report
 */
export function generateDailySalesPDF(data: {
  date: string;
  generatedBy?: string;
  items: Array<{
    code: string;
    name: string;
    brand: string;
    sold_on_date: number;
    balance: number;
    status: string;
  }>;
  totalSoldToday: number;
}) {
  const doc = createBaseDoc({
    reportTitle: `Daily Sales Report — ${data.date}`,
    periodText: data.date,
    generatedBy: data.generatedBy,
  });

  // KPI Summary box
  doc.setFillColor(241, 245, 249);
  doc.roundedRect(14, 37, 182, 16, 2, 2, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(30, 41, 59);
  doc.text(`Report Date: ${data.date}`, 18, 47);
  doc.text(`Total Metres Sold: ${data.totalSoldToday.toLocaleString()} m`, 110, 47);

  // Table
  const tableData = data.items.map((item, idx) => [
    idx + 1,
    item.code,
    item.name,
    item.brand,
    `${item.sold_on_date > 0 ? item.sold_on_date.toFixed(1) : '-'} m`,
    `${item.balance.toFixed(1)} m`,
    item.status,
  ]);

  autoTable(doc, {
    startY: 57,
    head: [['#', 'Lipping Code', 'Lipping Name', 'Brand', 'Quantity Sold', 'Remaining Stock', 'Status']],
    body: tableData,
    theme: 'grid',
    headStyles: {
      fillColor: [30, 41, 59],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8.5,
      halign: 'center',
    },
    styles: {
      fontSize: 8,
      cellPadding: 2,
    },
    columnStyles: {
      0: { halign: 'center', cellWidth: 10 },
      1: { fontStyle: 'bold', cellWidth: 26 },
      2: { cellWidth: 44 },
      3: { cellWidth: 28 },
      4: { halign: 'right', cellWidth: 26 },
      5: { halign: 'right', fontStyle: 'bold', cellWidth: 26 },
      6: { halign: 'center', cellWidth: 22 },
    },
    didParseCell: (data) => {
      if (data.section === 'body' && data.column.index === 6) {
        if (data.cell.raw === 'OUT OF STOCK') {
          data.cell.styles.textColor = [220, 38, 38];
          data.cell.styles.fontStyle = 'bold';
        } else if (data.cell.raw === 'LOW STOCK') {
          data.cell.styles.textColor = [217, 119, 6];
          data.cell.styles.fontStyle = 'bold';
        } else {
          data.cell.styles.textColor = [22, 101, 52];
        }
      }
    },
  });

  addDocFooter(doc);
  doc.save(`Mabri_Daily_Sales_Report_${data.date}.pdf`);
}

