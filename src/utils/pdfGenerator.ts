/**
 * Official Vector Logo Drawing Helper for jsPDF
 */
export function drawMabriLogo(
  doc: jsPDF,
  x: number,
  y: number,
  height: number = 10,
  textColor: [number, number, number] = [30, 41, 59]
) {
  const s = height / 120;
  // Left cyan pillar
  doc.setFillColor(103, 200, 247);
  doc.rect(x + 0 * s, y + 35 * s, 38 * s, 75 * s, 'F');
  doc.triangle(
    x + 0 * s, y + 35 * s,
    x + 38 * s, y + 12 * s,
    x + 38 * s, y + 35 * s,
    'F'
  );
  // Right cyan pillar
  doc.rect(x + 122 * s, y + 35 * s, 38 * s, 75 * s, 'F');
  doc.triangle(
    x + 122 * s, y + 35 * s,
    x + 122 * s, y + 12 * s,
    x + 160 * s, y + 35 * s,
    'F'
  );
  // Deep blue chevron V
  doc.setFillColor(28, 43, 136);
  doc.triangle(
    x + 0 * s, y + 0 * s,
    x + 52 * s, y + 0 * s,
    x + 80 * s, y + 80 * s,
    'F'
  );
  doc.triangle(
    x + 108 * s, y + 0 * s,
    x + 160 * s, y + 0 * s,
    x + 80 * s, y + 80 * s,
    'F'
  );
  doc.triangle(
    x + 54 * s, y + 120 * s,
    x + 106 * s, y + 120 * s,
    x + 80 * s, y + 78 * s,
    'F'
  );

  // Mabri Wordmark
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(height * 1.5);
  doc.setTextColor(textColor[0], textColor[1], textColor[2]);
  doc.text('Mabri', x + 172 * s, y + height * 0.82);
}

